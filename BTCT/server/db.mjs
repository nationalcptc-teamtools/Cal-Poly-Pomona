import { Database } from 'bun:sqlite';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dbPath = process.env.DB_PATH || path.join(__dirname, 'data.sqlite');

export const db = new Database(dbPath);
db.exec('PRAGMA journal_mode = WAL;');
// WAL + synchronous NORMAL is the recommended pairing: without it Bun's
// SQLite stays at FULL and fsyncs the WAL on EVERY commit, which made a
// 200-record cmdlog batch cost 200 fsyncs. NORMAL only risks losing the
// last transactions on an OS crash, never corruption.
db.exec('PRAGMA synchronous = NORMAL;');
// Wait for a competing writer (backup, import) instead of failing at once
// with SQLITE_BUSY, and keep the WAL file from staying huge after a spike.
db.exec('PRAGMA busy_timeout = 5000;');
db.exec(`PRAGMA journal_size_limit = ${64 * 1024 * 1024};`);

db.exec(`
  CREATE TABLE IF NOT EXISTS users (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    username    TEXT UNIQUE NOT NULL COLLATE NOCASE,
    salt        TEXT NOT NULL,
    hash        TEXT NOT NULL,
    iter        INTEGER NOT NULL,
    color       TEXT NOT NULL,
    avatar      TEXT,
    is_admin    INTEGER NOT NULL DEFAULT 0,
    created_at  INTEGER NOT NULL
  );

  CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );

  -- Binary assets (Typst report screenshots + custom fonts). Only the
  -- metadata lives here; the bytes are files under ASSETS_DIR keyed by id.
  -- The workspace-facing record (display name, crop rect) is in the shared
  -- Yjs doc: this table is the server's own inventory of what it stores,
  -- so it can serve the right Content-Type and clean up orphaned files.
  CREATE TABLE IF NOT EXISTS assets (
    id          TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL,
    kind        TEXT NOT NULL,          -- 'image' | 'font'
    filename    TEXT NOT NULL,          -- sanitized; also the Typst VFS name
    mime        TEXT NOT NULL,
    size        INTEGER NOT NULL,
    uploaded_by INTEGER,
    created_at  INTEGER NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_assets_ws ON assets(workspace_id, created_at DESC);

  -- Team command log. Each row is one whitelisted command captured by a
  -- btct-cmdlog agent on an operator's box and shipped here. This is the
  -- durable archive (unbounded); the shared Yjs doc holds only a bounded live
  -- window for the UI. The 'id' is generated by the agent (see cmdlog.mjs) so
  -- ingest is idempotent and the later exit/duration update finds its row.
  CREATE TABLE IF NOT EXISTS command_logs (
    id           TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL,
    operator     TEXT NOT NULL,
    command      TEXT NOT NULL,          -- redacted unless the agent ran --no-redact
    tool         TEXT NOT NULL,          -- matched whitelist entry
    cwd          TEXT,
    host         TEXT,
    local_user   TEXT,
    shell_pid    INTEGER,
    started_at   INTEGER NOT NULL,       -- agent clock (epoch ms)
    received_at  INTEGER NOT NULL,       -- server clock: keeps skew debuggable
    exit_code    INTEGER,                -- NULL until the completion event lands
    duration_ms  INTEGER,
    redacted     INTEGER NOT NULL DEFAULT 1
  );
  CREATE INDEX IF NOT EXISTS idx_cmdlog_ws ON command_logs(workspace_id, started_at DESC);
  CREATE INDEX IF NOT EXISTS idx_cmdlog_op ON command_logs(workspace_id, operator, started_at DESC);

  -- Page version history (history.mjs). One row per version. The snapshot
  -- column is a Yjs snapshot (state vector + delete set) against the page's
  -- GC-off twin file under HISTORY_DIR; rows imported from the old
  -- pageSnapshots CRDT map carry the full document state instead. Bytes
  -- only: the server never reads what a page says.
  CREATE TABLE IF NOT EXISTS page_versions (
    id           TEXT PRIMARY KEY,
    page_id      TEXT NOT NULL,
    workspace_id TEXT,
    created_at   INTEGER NOT NULL,
    trigger      TEXT NOT NULL,          -- auto | named | restore | import
    name         TEXT,
    created_by   INTEGER,
    changed_by   TEXT NOT NULL DEFAULT '[]',  -- JSON array of user ids (0 = unknown)
    snapshot     BLOB,
    state        BLOB,
    size         INTEGER NOT NULL DEFAULT 0
  );
  CREATE INDEX IF NOT EXISTS idx_page_versions_page ON page_versions(page_id, created_at DESC);
`);

// Best-effort migration for databases predating the is_admin column.
try {
  const cols = db.prepare(`PRAGMA table_info(users)`).all();
  if (!cols.some((c) => c.name === 'is_admin')) {
    db.exec(`ALTER TABLE users ADD COLUMN is_admin INTEGER NOT NULL DEFAULT 0`);
  }
  if (!cols.some((c) => c.name === 'avatar')) {
    db.exec(`ALTER TABLE users ADD COLUMN avatar TEXT`);
  }
  if (!cols.some((c) => c.name === 'prefs')) {
    db.exec(`ALTER TABLE users ADD COLUMN prefs TEXT`);
  }
} catch (err) {
  console.warn('[db] migration check failed:', err?.message || err);
}

const insertUser = db.prepare(
  `INSERT INTO users (username, salt, hash, iter, color, is_admin, created_at)
   VALUES ($username, $salt, $hash, $iter, $color, $is_admin, $created_at)`,
);
const findByUsername = db.prepare(
  `SELECT * FROM users WHERE username = ? COLLATE NOCASE`,
);
const findFullById = db.prepare(`SELECT * FROM users WHERE id = ?`);
const listAllUsers = db.prepare(
  `SELECT id, username, color, avatar, is_admin, created_at FROM users ORDER BY id ASC`,
);
const deleteUserById = db.prepare(`DELETE FROM users WHERE id = ?`);
const setAdminById = db.prepare(`UPDATE users SET is_admin = ? WHERE id = ?`);
const updatePasswordById = db.prepare(
  `UPDATE users SET salt = $salt, hash = $hash, iter = $iter WHERE id = $id`,
);
const setColorById = db.prepare(`UPDATE users SET color = ? WHERE id = ?`);
const setUsernameById = db.prepare(`UPDATE users SET username = ? WHERE id = ?`);
const setPrefsById = db.prepare(`UPDATE users SET prefs = ? WHERE id = ?`);
const countAdmins = db.prepare(
  `SELECT COUNT(*) AS n FROM users WHERE is_admin = 1`,
);

// Same as the first eight of SWATCHES in src/lib/swatches.ts.
const PRESENCE_COLORS = [
  '#ef4444', '#f59e0b', '#10b981', '#3b82f6',
  '#8b5cf6', '#ec4899', '#14b8a6', '#f97316',
];

export function createUser({ username, salt, hash, iter, isAdmin = false }) {
  const color = PRESENCE_COLORS[Math.floor(Math.random() * PRESENCE_COLORS.length)];
  const info = insertUser.run({
    $username: username,
    $salt: salt,
    $hash: hash,
    $iter: iter,
    $color: color,
    $is_admin: isAdmin ? 1 : 0,
    $created_at: Date.now(),
  });
  return findFullById.get(Number(info.lastInsertRowid));
}

