export function renamePageVersion(pageId, id, name, createdBy) {
  db.query(`UPDATE page_versions SET name = ?, created_by = COALESCE(?, created_by) WHERE page_id = ? AND id = ?`)
    .run(name, createdBy ?? null, pageId, id);
}

export function publicUser(row) {
  if (!row) return null;
  return {
    id: row.id,
    username: row.username,
    color: row.color,
    isAdmin: !!row.is_admin,
    prefs: parsePrefs(row.prefs),
  };
}

// Defensive JSON parse for the stored prefs blob. Older rows (and rows that
// have never saved prefs) have NULL here; return an empty object so clients
// can merge their own defaults over it.
function parsePrefs(raw) {
  if (!raw) return {};
  try {
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

/**
 * Close the database for a clean shutdown: fold the WAL back into the main
 * file first, so a stopped container's /data holds one self-contained file.
 * Anything that touches `db` afterwards throws, so call this last.
 */
export function closeDb() {
  try { db.exec('PRAGMA wal_checkpoint(TRUNCATE);'); } catch { /* close anyway */ }
  db.close();
}
