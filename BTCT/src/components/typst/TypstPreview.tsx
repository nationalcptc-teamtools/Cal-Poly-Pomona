/** One guess at what a preview click corresponds to in the source. */
export interface SourceCandidate {
  text: string;
  occurrence: number;
}

/**
 * A rendered run that Typst generated rather than the author typing it:
 * a heading number, a figure counter. These have no source text to jump to,
 * so they're tried *after* their neighbours.
 *
 * Deliberately narrow: a short run of digits and dots. Real content that
 * looks numeric (an IP like `10.0.0.5`, a CVSS score in a table) stays a
 * first-class candidate.
 */
function looksAutoGenerated(text: string): boolean {
  return /^[\d.]{1,4}$/.test(text.trim());
}

/**
 * Resolve a click to ordered source candidates, best guess first.
 *
 * typst.ts emits a hidden selection layer: one `<foreignObject>` per text
 * run, containing a `.tsel` div with the literal characters. We hit-test
 * against those boxes geometrically rather than trusting `event.target`,
 * because the `.tsel` divs are `position: fixed` (typst.ts's trick for making
 * text selectable across the SVG), so whatever the browser reports as the
 * event target isn't reliably the run under the cursor.
 *
 * Falls back to the nearest box when the click lands in a margin or between
 * lines, so clicking roughly at something still works.
 *
 * `precedingTexts` are the runs of every page before `container`'s, in
 * order: an occurrence index only means something counted from the start of
 * the document, and `container` is a single page.
 */
/** Where the rendered pages live: the shadow root, or one page card inside it. */
type Scope = Element | ShadowRoot;

function textRunAtPoint(
  container: Scope,
  clientX: number,
  clientY: number,
  precedingTexts: readonly string[] = [],
): SourceCandidate[] {
  const objects = Array.from(container.querySelectorAll('foreignObject'));
  if (objects.length === 0) return [];

  const texts = objects.map((o) => o.textContent ?? '');

  let bestIndex = -1;
  let bestDistance = Infinity;
  for (let i = 0; i < objects.length; i++) {
    if (!texts[i]!.trim()) continue;
    const r = objects[i]!.getBoundingClientRect();
    if (r.width === 0 && r.height === 0) continue;

    // Distance to the box: zero when the point is inside it.
    const dx = Math.max(r.left - clientX, 0, clientX - r.right);
    const dy = Math.max(r.top - clientY, 0, clientY - r.bottom);
    const distance = Math.hypot(dx, dy);
    if (distance < bestDistance) {
      bestDistance = distance;
      bestIndex = i;
      if (distance === 0) break; // inside a run: can't do better
    }
  }

  if (bestIndex === -1) return [];
  // Ignore a click far from any text (empty page area) rather than yanking
  // the cursor to something arbitrary.
  if (bestDistance > 120) return [];

  // Offer the neighbours as fallbacks. Clicking a heading's number should
  // land on the heading, and a run whose text Typst transformed beyond
  // recognition shouldn't dead-end when the run beside it would resolve.
  const order = [bestIndex, bestIndex + 1, bestIndex - 1, bestIndex + 2];
  if (looksAutoGenerated(texts[bestIndex]!)) {
    // A counter has no source of its own: prefer the content it labels.
    order.splice(0, 1);
    order.push(bestIndex);
  }

  const allTexts = precedingTexts.length > 0 ? [...precedingTexts, ...texts] : texts;
  const offset = precedingTexts.length;
  const seen = new Set<number>();
  const candidates: SourceCandidate[] = [];
  for (const i of order) {
    if (i < 0 || i >= texts.length || seen.has(i)) continue;
    seen.add(i);
    if (!texts[i]!.trim()) continue;
    candidates.push({ text: texts[i]!, occurrence: occurrenceIndex(allTexts, offset + i) });
  }
  return candidates;
}

/** The data-URI href of the rendered image under the pointer, if any. */
function imageHrefAtPoint(
  container: Scope,
  clientX: number,
  clientY: number,
): string | null {
  let best: { href: string; area: number } | null = null;
  for (const img of Array.from(container.querySelectorAll('svg image'))) {
    const r = img.getBoundingClientRect();
    if (clientX < r.left || clientX > r.right || clientY < r.top || clientY > r.bottom) continue;
    const href = img.getAttribute('href') || img.getAttribute('xlink:href');
    if (!href) continue;
    const area = r.width * r.height;
    // Prefer the smallest hit: a figure nested over a full-page background
    // image should win over the background.
    if (!best || area < best.area) best = { href, area };
  }
  return best?.href ?? null;
}

